"""Lifecycle → Jira sync — the engine that fires Jira writes when a
Bifrost task transitions.

This is the bridge between ``task_lifecycle.transition()`` and
``jira_writer``. The transition function calls ``on_transition()``
here AFTER its own audit row lands, in a fresh session, so a Jira
write failure never rolls back the underlying Bifrost transition.
The two stay decoupled — Jira is a projection of Bifrost state, not
its source of truth (re: the design doc's "no continuous sync"
constraint).

Hook table (canonical):

  PLAN_READY  → CREATE issue (if not already linked) + comment with
                chat conversation deep-link if conversation_id is set
  EXECUTING   → TRANSITION to "In Progress" + comment with branch
  SUCCESS     → TRANSITION to "In Review" + comment with PR URL
  PR_MERGED   → TRANSITION to "Done"
  CANCELLED   → TRANSITION to "Won't Do" + comment with reason
  BLOCKED     → COMMENT only (don't move state)

Failure semantics:
  ``JiraWriteSkipped`` (no MCP / not authenticated) → log + return.
    The task lifecycle proceeds; the operator can re-sync later.
  ``JiraWriteFailed`` (MCP returned an error) → audit row already
    recorded the failure; we log + return. UI surfaces the audit row
    so the operator can retry.

Public entry points:

  * ``on_transition(session, task_id, old, new, reason)`` — called
    from ``task_lifecycle.transition()``. Wraps the right
    side-effect for the new state.

  * ``ensure_jira_for_task(session, task_id, ...)`` — explicit
    create-if-missing. Used by the spawn modal AND the lifecycle
    hook on PLAN_READY.

  * ``rebind_to_project(...)`` — unlink + recreate (used by retract).
"""

from __future__ import annotations

import contextlib
import logging
from typing import Any

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from bifrost.actions.jira_state_map import jira_state_for
from bifrost.actions.jira_writer import (
    JiraIssueCreate,
    JiraWriteFailed,
    JiraWriteSkipped,
    add_comment,
    create_issue,
    transition_issue,
)
from bifrost.actions.project_resolver import (
    ResolvedProject,
    project_from_jira_key,
    resolve_for_task,
)
from bifrost.actions.task_lifecycle import TaskState

logger = logging.getLogger(__name__)


# ── helpers ──────────────────────────────────────────────────────────


async def _load_task_basics(
    session: AsyncSession,
    task_id: str,
) -> dict[str, Any] | None:
    row = (
        (
            await session.execute(
                text(
                    "SELECT id::text AS id, title, intent_text, jira_key, "
                    "       conversation_id::text, created_from, "
                    "       branch_name, pr_url, "
                    "       acceptance_criteria "
                    "FROM tasks WHERE id = CAST(:id AS uuid)"
                ),
                {"id": task_id},
            )
        )
        .mappings()
        .first()
    )
    return dict(row) if row else None


def _format_description(task: dict[str, Any]) -> str:
    intent = (task.get("intent_text") or "").strip()
    ac = task.get("acceptance_criteria") or []
    parts: list[str] = []
    if intent:
        parts.append("## Intent\n" + intent)
    if ac:
        parts.append(
            "## Acceptance criteria\n" + "\n".join(f"- {item}" for item in ac if str(item).strip()),
        )
    parts.append(
        "\n---\n_Generated by Bifrost. The conversation that "
        "produced this task drives the work; comments will reflect "
        "Bifrost's lifecycle state changes (executing → in review → "
        "done)._",
    )
    return "\n\n".join(parts)


# ── public: ensure Jira issue exists ────────────────────────────────


async def ensure_jira_for_task(
    session: AsyncSession,
    *,
    task_id: str,
    project_key: str | None = None,
    actor: str = "system",
) -> str | None:
    """Create the task's Jira issue if not yet linked. Returns the
    Jira key (existing or freshly created), or ``None`` if no Jira
    project could be resolved (caller should surface the picker)."""
    task = await _load_task_basics(session, task_id)
    if task is None:
        return None
    if task["jira_key"]:
        return str(task["jira_key"])

    resolved: ResolvedProject | None = None
    if project_key:
        resolved = ResolvedProject(
            project_key=project_key.upper(),
            source="explicit",
        )
    else:
        resolved = await resolve_for_task(session, task_id=task_id)
    if resolved is None or not resolved.project_key:
        logger.info(
            "ensure_jira_for_task: no project resolved for task=%s; deferring",
            task_id,
        )
        return None

    body = JiraIssueCreate(
        project_key=resolved.project_key,
        summary=str(task.get("title") or "")[:240] or "Bifrost task",
        description=_format_description(task),
        issue_type="Task",
        labels=["bifrost"],
    )
    try:
        result = await create_issue(
            session,
            task_id=task_id,
            body=body,
            actor=actor,
        )
        logger.info(
            "ensure_jira_for_task: created %s for task=%s",
            result.key,
            task_id,
        )
        return result.key
    except JiraWriteSkipped as exc:
        logger.warning(
            "ensure_jira_for_task: Jira write skipped (no MCP) for task=%s: %s",
            task_id,
            exc,
        )
        return None
    except JiraWriteFailed as exc:
        logger.warning(
            "ensure_jira_for_task: Jira write failed for task=%s: %s",
            task_id,
            exc,
        )
        return None


# ── public: per-state side effect ────────────────────────────────────


async def on_transition(
    session_factory: async_sessionmaker[AsyncSession],
    *,
    task_id: str,
    old_state: TaskState,
    new_state: TaskState,
    reason: str = "",
    actor: str = "system",
) -> None:
    """Fire the Jira side-effect for a transition. Runs in a fresh
    session so a Jira-write failure cannot affect the underlying
    Bifrost transition (which already committed)."""
    target_jira = jira_state_for(new_state)
    if target_jira is None and new_state != TaskState.PLAN_READY and new_state != TaskState.BLOCKED:
        return  # no Jira side-effect for this state

    async with session_factory() as session:
        try:
            await _dispatch_state_effect(
                session,
                task_id=task_id,
                old_state=old_state,
                new_state=new_state,
                reason=reason,
                actor=actor,
            )
            await session.commit()
        except Exception:  # noqa: BLE001
            logger.exception(
                "on_transition: dispatch failed task=%s %s→%s",
                task_id,
                old_state,
                new_state,
            )
            await session.rollback()


async def _dispatch_state_effect(
    session: AsyncSession,
    *,
    task_id: str,
    old_state: TaskState,
    new_state: TaskState,
    reason: str,
    actor: str,
) -> None:
    task = await _load_task_basics(session, task_id)
    if task is None:
        return

    # PLAN_READY → create issue (if missing) + initial comment
    if new_state == TaskState.PLAN_READY:
        jira_key = await ensure_jira_for_task(
            session,
            task_id=task_id,
            actor=actor,
        )
        if jira_key and task.get("conversation_id"):
            try:
                await add_comment(
                    session,
                    task_id=task_id,
                    jira_key=jira_key,
                    body=(
                        "Task is plan-ready in Bifrost. Source "
                        f"conversation: {task['conversation_id']}"
                    ),
                    actor=actor,
                )
            except (JiraWriteSkipped, JiraWriteFailed):
                pass  # already audited
        return

    # EXECUTING → In Progress + branch comment
    if new_state == TaskState.EXECUTING:
        jira_key = task.get("jira_key") or await ensure_jira_for_task(
            session,
            task_id=task_id,
            actor=actor,
        )
        if not jira_key:
            return
        try:
            await transition_issue(
                session,
                task_id=task_id,
                jira_key=jira_key,
                target_state=jira_state_for(
                    TaskState.EXECUTING,
                    project_key=project_from_jira_key(jira_key) or "",
                )
                or "In Progress",
                actor=actor,
                before_state=old_state.value,
                after_state=new_state.value,
            )
            branch = task.get("branch_name")
            if branch:
                await add_comment(
                    session,
                    task_id=task_id,
                    jira_key=jira_key,
                    body=f"Bifrost is executing on branch `{branch}`.",
                    actor=actor,
                )
        except (JiraWriteSkipped, JiraWriteFailed):
            pass
        return

    # SUCCESS → In Review + PR comment
    if new_state == TaskState.SUCCESS:
        jira_key = task.get("jira_key")
        if not jira_key:
            return
        try:
            await transition_issue(
                session,
                task_id=task_id,
                jira_key=jira_key,
                target_state=jira_state_for(
                    TaskState.SUCCESS,
                    project_key=project_from_jira_key(jira_key) or "",
                )
                or "In Review",
                actor=actor,
                before_state=old_state.value,
                after_state=new_state.value,
            )
            pr_url = task.get("pr_url")
            if pr_url:
                await add_comment(
                    session,
                    task_id=task_id,
                    jira_key=jira_key,
                    body=f"Pull request open for review: {pr_url}",
                    actor=actor,
                )
        except (JiraWriteSkipped, JiraWriteFailed):
            pass
        return

    # PR_MERGED → Done
    if new_state == TaskState.PR_MERGED:
        jira_key = task.get("jira_key")
        if not jira_key:
            return
        with contextlib.suppress(JiraWriteSkipped, JiraWriteFailed):
            await transition_issue(
                session,
                task_id=task_id,
                jira_key=jira_key,
                target_state=jira_state_for(
                    TaskState.PR_MERGED,
                    project_key=project_from_jira_key(jira_key) or "",
                )
                or "Done",
                actor=actor,
                before_state=old_state.value,
                after_state=new_state.value,
            )
        return

    # CANCELLED → Won't Do + reason comment
    if new_state == TaskState.CANCELLED:
        jira_key = task.get("jira_key")
        if not jira_key:
            return
        try:
            await transition_issue(
                session,
                task_id=task_id,
                jira_key=jira_key,
                target_state=jira_state_for(
                    TaskState.CANCELLED,
                    project_key=project_from_jira_key(jira_key) or "",
                )
                or "Won't Do",
                actor=actor,
                before_state=old_state.value,
                after_state=new_state.value,
            )
            if reason:
                await add_comment(
                    session,
                    task_id=task_id,
                    jira_key=jira_key,
                    body=f"Cancelled in Bifrost. Reason: {reason}",
                    actor=actor,
                )
        except (JiraWriteSkipped, JiraWriteFailed):
            pass
        return

    # BLOCKED → comment only
    if new_state == TaskState.BLOCKED:
        jira_key = task.get("jira_key")
        if not jira_key:
            return
        with contextlib.suppress(JiraWriteSkipped, JiraWriteFailed):
            await add_comment(
                session,
                task_id=task_id,
                jira_key=jira_key,
                body=(f"Bifrost task is blocked. Reason: {reason or '(no reason given)'}"),
                actor=actor,
            )
        return
